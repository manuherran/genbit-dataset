  cantidad INT NOT NULL,
  PRIMARY KEY (id_producto, id_pieza),
  CONSTRAINT fk_producto_pieza_1 FOREIGN KEY (id_producto) REFERENCES t_producto (id),
  CONSTRAINT fk_producto_pieza_2 FOREIGN KEY (id_pieza) REFERENCES t_pieza (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Pedidos de clientes, gestionados por un empleado de ventas.
CREATE TABLE t_pedido (
  id INT NOT NULL,
  id_cliente INT NOT NULL,
  id_empleado INT NULL,
  fecha_pedido DATE NOT NULL,
  fecha_entrega DATE NULL,
  id_planeta_destino INT NOT NULL,
  estado VARCHAR(30) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_pedido_1 FOREIGN KEY (id_cliente) REFERENCES t_cliente (id),
  CONSTRAINT fk_pedido_2 FOREIGN KEY (id_empleado) REFERENCES t_empleado (id),
  CONSTRAINT fk_pedido_3 FOREIGN KEY (id_planeta_destino) REFERENCES t_planeta (id)
