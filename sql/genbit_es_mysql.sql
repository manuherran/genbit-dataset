-- Paso 1: tablas, claves primarias y foráneas

-- Planetas, lunas y estaciones donde opera GenBit.
CREATE TABLE t_planeta (
  id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  sistema_estelar VARCHAR(50) NOT NULL,
  tipo VARCHAR(50) NOT NULL,
  distancia_al DECIMAL(8,2) NOT NULL,
  gravedad_g DECIMAL(4,2) NOT NULL,
  poblacion BIGINT NOT NULL,
  habitable BOOLEAN NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Empresas del grupo GenBit y socias. id_matriz apunta a la empresa matriz.
CREATE TABLE t_empresa (
  id INT NOT NULL,
  siglas VARCHAR(10) NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  sector VARCHAR(50) NOT NULL,
  id_planeta_sede INT NOT NULL,
  anio_fundacion INT NOT NULL,
  id_matriz INT NULL,
  num_empleados INT NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_empresa_1 FOREIGN KEY (id_planeta_sede) REFERENCES t_planeta (id),
  CONSTRAINT fk_empresa_2 FOREIGN KEY (id_matriz) REFERENCES t_empresa (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Oficinas y laboratorios de cada empresa.
CREATE TABLE t_oficina (
  id INT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  id_empresa INT NOT NULL,
  id_planeta INT NOT NULL,
  ciudad VARCHAR(50) NOT NULL,
  capacidad INT NOT NULL,
  fecha_apertura DATE NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_oficina_1 FOREIGN KEY (id_empresa) REFERENCES t_empresa (id),
  CONSTRAINT fk_oficina_2 FOREIGN KEY (id_planeta) REFERENCES t_planeta (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Empleados de GenBit. id_jefe es una relación reflexiva (empleado → jefe).
CREATE TABLE t_empleado (
  id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NULL,
  email VARCHAR(100) NOT NULL,
  puesto VARCHAR(80) NOT NULL,
  departamento VARCHAR(50) NOT NULL,
  id_oficina INT NULL,
  id_jefe INT NULL,
  fecha_alta DATE NOT NULL,
  salario DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_empleado_1 FOREIGN KEY (id_oficina) REFERENCES t_oficina (id),
  CONSTRAINT fk_empleado_2 FOREIGN KEY (id_jefe) REFERENCES t_empleado (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Móviles de empresa. Un empleado puede tener varios; algunos no están asignados.
CREATE TABLE t_movil (
  numero VARCHAR(15) NOT NULL,
  puk VARCHAR(10) NOT NULL,
  modelo VARCHAR(50) NOT NULL,
  operador VARCHAR(50) NOT NULL,
  id_empleado INT NULL,
  PRIMARY KEY (numero),
  CONSTRAINT fk_movil_1 FOREIGN KEY (id_empleado) REFERENCES t_empleado (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Clientes de toda la galaxia (humanos y no humanos).
CREATE TABLE t_cliente (
  id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NULL,
  especie VARCHAR(50) NOT NULL,
  email VARCHAR(100) NULL,
  id_planeta INT NOT NULL,
  id_empresa INT NULL,
  fecha_registro DATE NOT NULL,
  nivel VARCHAR(20) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_cliente_1 FOREIGN KEY (id_planeta) REFERENCES t_planeta (id),
  CONSTRAINT fk_cliente_2 FOREIGN KEY (id_empresa) REFERENCES t_empresa (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Proveedores de piezas.
CREATE TABLE t_proveedor (
  id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NOT NULL,
  razon_social VARCHAR(80) NOT NULL,
  especialidad VARCHAR(50) NOT NULL,
  id_planeta INT NOT NULL,
  valoracion DECIMAL(2,1) NOT NULL,
  email VARCHAR(100) NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_proveedor_1 FOREIGN KEY (id_planeta) REFERENCES t_planeta (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Inversores. Algunos también son empleados (id_empleado).
CREATE TABLE t_inversor (
  id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NOT NULL,
  id_empleado INT NULL,
  id_empresa INT NOT NULL,
  numero_acciones INT NOT NULL,
  fecha_inversion DATE NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_inversor_1 FOREIGN KEY (id_empleado) REFERENCES t_empleado (id),
  CONSTRAINT fk_inversor_2 FOREIGN KEY (id_empresa) REFERENCES t_empresa (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Proyectos de investigación (genética, física cuántica, neurociencia…).
CREATE TABLE t_proyecto (
  id INT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  area VARCHAR(50) NOT NULL,
  id_empresa INT NOT NULL,
  id_responsable INT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NULL,
  presupuesto DECIMAL(14,2) NOT NULL,
  estado VARCHAR(20) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_proyecto_1 FOREIGN KEY (id_empresa) REFERENCES t_empresa (id),
  CONSTRAINT fk_proyecto_2 FOREIGN KEY (id_responsable) REFERENCES t_empleado (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Relación N-M entre empleados y proyectos.
CREATE TABLE t_asignacion (
  id_empleado INT NOT NULL,
  id_proyecto INT NOT NULL,
  rol VARCHAR(30) NOT NULL,
  horas_semana INT NOT NULL,
  PRIMARY KEY (id_empleado, id_proyecto),
  CONSTRAINT fk_asignacion_1 FOREIGN KEY (id_empleado) REFERENCES t_empleado (id),
  CONSTRAINT fk_asignacion_2 FOREIGN KEY (id_proyecto) REFERENCES t_proyecto (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Pacientes de los ensayos clínicos de GenBit.
CREATE TABLE t_paciente (
  id INT NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NULL,
  fecha_nacimiento DATE NOT NULL,
  especie VARCHAR(50) NOT NULL,
  grupo_sanguineo VARCHAR(3) NULL,
  id_planeta INT NOT NULL,
  id_proyecto INT NULL,
  fecha_ingreso DATE NOT NULL,
  estado VARCHAR(30) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_paciente_1 FOREIGN KEY (id_planeta) REFERENCES t_planeta (id),
  CONSTRAINT fk_paciente_2 FOREIGN KEY (id_proyecto) REFERENCES t_proyecto (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Suscriptores del boletín. Sin claves foráneas: se cruzan por email.
CREATE TABLE t_suscriptor (
  email VARCHAR(100) NOT NULL,
  fecha_alta DATE NOT NULL,
  idioma VARCHAR(2) NOT NULL,
  boletin VARCHAR(50) NOT NULL,
  activo BOOLEAN NOT NULL,
  PRIMARY KEY (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Líneas de producto.
CREATE TABLE t_linea_de_producto (
  id INT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  descripcion VARCHAR(200) NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Productos a la venta. Precios en créditos galácticos (CG).
CREATE TABLE t_producto (
  id INT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  id_linea INT NOT NULL,
  id_proyecto INT NULL,
  precio DECIMAL(12,2) NOT NULL,
  stock INT NOT NULL,
  fecha_lanzamiento DATE NOT NULL,
  peso_kg DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_producto_1 FOREIGN KEY (id_linea) REFERENCES t_linea_de_producto (id),
  CONSTRAINT fk_producto_2 FOREIGN KEY (id_proyecto) REFERENCES t_proyecto (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Piezas y componentes.
CREATE TABLE t_pieza (
  id INT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  material VARCHAR(50) NOT NULL,
  id_proveedor INT NULL,
  coste DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_pieza_1 FOREIGN KEY (id_proveedor) REFERENCES t_proveedor (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Lista de materiales: qué piezas lleva cada producto (N-M).
